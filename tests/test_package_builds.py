"""Exercise the build hooks through the package backend and pip."""

import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import unittest
import zipfile

from scripts.prepare_schemas import prepare


@unittest.skipUnless(importlib.util.find_spec("setuptools_scm"), "requires setuptools-scm")
class PackageBuildTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name) / "project"
        self.root.mkdir()
        repository = Path(__file__).resolve().parents[1]
        for name in ("src", "scripts"):
            shutil.copytree(repository / name, self.root / name,
                            ignore=shutil.ignore_patterns("__pycache__", "*.egg-info", "_generated_schemas", "_version.py"))
        for name in ("pyproject.toml", "setup.py", "MANIFEST.in", "README.md", "LICENSE", ".gitignore"):
            shutil.copy2(repository / name, self.root / name)
        self.originals = {path.name: path.read_bytes() for path in (self.root / "src/tokamap/schemas").glob("*.json")}
        self.environment = dict(os.environ)
        for name in ("TOKAMAP_SCHEMA_VERSION", "TOKAMAP_SCHEMA_DEVELOP", "SETUPTOOLS_SCM_PRETEND_VERSION", "SETUPTOOLS_SCM_PRETEND_VERSION_FOR_TOKAMAP"):
            self.environment.pop(name, None)
        self.run_command("git", "init", "-q")
        self.run_command("git", "config", "user.name", "Test")
        self.run_command("git", "config", "user.email", "test@example.com")
        self.run_command("git", "add", ".")
        self.run_command("git", "commit", "-qm", "Test project")
        self.run_command("git", "tag", "v0.3.2")

    def run_command(self, *args, cwd=None):
        result = subprocess.run(args, cwd=cwd or self.root, env=self.environment,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        self.assertEqual(result.returncode, 0, result.stdout)
        return result.stdout

    def build(self, kind, root=None):
        root = root or self.root
        self.run_command(sys.executable, "-c",
                         f"from setuptools.build_meta import build_{kind}; build_{kind}('dist')", cwd=root)
        return next((root / "dist").glob("*.whl" if kind == "wheel" else "*.tar.gz"))

    def assert_sources_unchanged(self):
        for name, content in self.originals.items():
            self.assertEqual((self.root / "src/tokamap/schemas" / name).read_bytes(), content)
        self.assertEqual(self.run_command("git", "diff", "--exit-code"), "")

    def check_distribution_builds(self, expected_version):
        prepare(self.root)
        expected = {path.name: path.read_bytes() for path in (self.root / "build/schemas").glob("*.json")}
        direct_wheel = self.build("wheel")
        sdist = self.build("sdist")
        with tarfile.open(sdist) as archive:
            for name, content in expected.items():
                member = next(m for m in archive.getmembers() if m.name.endswith("/src/tokamap/schemas/" + name))
                self.assertEqual(archive.extractfile(member).read(), content)
            # These archives are generated by our own build within this test.
            archive.extractall(self.root / "unpacked", filter="data")
        unpacked = next((self.root / "unpacked").iterdir())
        self.assertFalse((unpacked / ".git").exists())
        metadata = json.loads((unpacked / ".schema-version.json").read_text())
        self.assertEqual(metadata["version"], expected_version)
        rebuilt_wheel = self.build("wheel", unpacked)
        for wheel in (direct_wheel, rebuilt_wheel):
            with zipfile.ZipFile(wheel) as archive:
                for name, content in expected.items():
                    self.assertEqual(archive.read("tokamap/schemas/" + name), content)
                self.assertFalse(any("_generated_schemas" in name for name in archive.namelist()))
        self.assert_sources_unchanged()

    def test_release_wheel_and_sdist_rebuild_preserve_exact_tag(self):
        self.check_distribution_builds("v0.3.2")
        self.assertTrue((self.root / "dist/tokamap-0.3.2-py3-none-any.whl").is_file())

    def test_development_sdist_retains_provisional_version_without_git(self):
        self.run_command("git", "commit", "--allow-empty", "-qm", "Development")
        self.check_distribution_builds("0.4")

    def test_normal_and_editable_installs_expose_generated_schemas(self):
        for mode in ("editable", "strict", "normal"):
            with self.subTest(mode=mode):
                target = Path(self.directory.name) / mode
                command = [sys.executable, "-m", "pip", "install", "--no-build-isolation", "--no-deps", "--target", str(target)]
                if mode != "normal":
                    command += ["--editable"]
                command += [str(self.root)]
                if mode == "strict":
                    command += ["--config-settings", "editable_mode=strict"]
                self.run_command(*command)
                output = self.run_command(sys.executable, "-S", "-c", (
                    "import site, json; "
                    f"site.addsitedir({str(target)!r}); "
                    "import tokamap; "
                    "print(json.dumps([json.loads(p.read_text())['$id'] "
                    "for p in sorted(tokamap.schemas_dir().glob('*.json'))]))"
                ), cwd=Path(self.directory.name))
                identifiers = json.loads(output)
                self.assertEqual(len(identifiers), 3)
                self.assertTrue(all("/v0.3.2/schemas/v0.3.2/" in uri for uri in identifiers))
                if mode == "normal":
                    self.assertFalse((target / "tokamap/_generated_schemas").exists())
                self.assert_sources_unchanged()
